// 별자리 그림 설정. 서버가 주지 않는 정보(별 위치·순서, 별 사이 선, 임시 그림)만 둔다.
// - 별자리 이름·별 개수·상태는 서버 값(API-906, API-402)을 쓴다. 여기 name 은 설정을 찾는 열쇠로만 쓴다.
// - 그림: 서버 Constellation.imageUrl 이 있으면 그것을 먼저 쓰고, 없으면 아래 image 를 쓴다.

// 0~1 비율 좌표. 별자리 칸(학습 홈 HUD 안쪽 328×288) 왼쪽 위가 (0, 0), 오른쪽 아래가 (1, 1).
export type StarPoint = { x: number; y: number };

// 선으로 잇는 두 별의 stars 배열 위치. 앞 번호가 작다.
export type StarLine = readonly [number, number];

// require('../../../assets/...') 결과(number) 또는 원격 주소.
export type ConstellationImage = number | { uri: string };

export type ConstellationLayout = {
  // 서버 별자리 이름(API-906 name). 띄어쓰기는 비교하지 않는다.
  name: string;
  // 코스 slug. 서버 응답에 slug 가 생기면 채우고, 이름보다 먼저 비교한다.
  slug?: string;
  // 배열 순서 = 레슨 순서(order 오름차순).
  stars: StarPoint[];
  lines: StarLine[];
  image?: ConstellationImage;
};

